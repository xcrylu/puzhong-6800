//===========宏定义===============
#define LED         P2        //LED控制端口
#define ON          0x00   
#define OFF            0xFF

#define KEY_ON  0
#define KEY_OFF 1

//======sfr bit定义==============
sbit KEY1=P3^0;
sbit KEY2=P3^1;

//======函数声明==================
void delay_ms_t0(uint x);    
void led_flash();
void led_flu_left(uchar x);
void led_flu_right(uchar x);


