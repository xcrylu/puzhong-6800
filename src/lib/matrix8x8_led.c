void write_74h595(unsigned char x)
{
    unsigned char i = 0;

    ST_CP = 0; //锁存低电平
    for(i = 0; i<8;i++)
    {
        SH_CP = 0;         //移位时钟低    
		    _nop_();        
        DS = x&0x80;       //准备数据最高位先移入    
		    _nop_();        
        SH_CP = 1;         //移入1位        
        _nop_();
        SH_CP = 0;    
        x<<= 1;
        
    }
    ST_CP = 0;
    _nop_();
    ST_CP = 1; //锁存数据
    _nop_();
    ST_CP = 0;
    _nop_();

}

void matrix_8x8_display(unsigned char buf[8])
{
    unsigned char i;
    //unsigned char x = 0x01;       
    MATRIX_DATA_PORT = 0xff;  //消隐  
  
    for(i = 0; i<8;i++)    {                    
        write_74h595(0x80>>i);        
        MATRIX_DATA_PORT = ~buf[i];      
        //P0 = ~buf[i];          
        delay_ms(1);        
    }    
}

void matrix_8x8_display_digit(unsigned char digit)
{    
    matrix_8x8_display(DigitPattern[digit]);
}


